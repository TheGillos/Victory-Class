/* ==========================================================================
   USS VICTORY NCC-9754-A — solid hull lofted from the reference orthographics

   The hull is a closed body: a dorsal shell and a ventral shell meeting at the
   chine, capped at the transom and the bow. Four nacelles are grown out of that
   surface rather than intersected with it — each rises from the hull skin and
   returns to it, so there is no seam and nothing to see through. Nacelle
   positions come from the emitter blobs measured in the top view: an inboard
   pair firing aft from the transom, an outboard pair with emitters at mid-hull.

   Section data in js/hull-data.js is generated by tools/extract-hull.py.
   Textures are the reference renders, planar-projected from directly above and
   below, so nacelle geometry automatically receives the nacelle art painted at
   that spot in the plan.

   Orientation: bow +X, dorsal +Y, starboard +Z. Station 0 is the transom.
   ========================================================================== */

import * as THREE from '../vendor/three.module.min.js';
import { HULL } from './hull-data.js';

export const SHIP = { length: 45.5, beam: 28.0, height: 4.9 };

const SPAN_SEGMENTS = 56;
const CHINE_SHARPNESS = 0.30;

const L = SHIP.length, HB = SHIP.beam / 2, HH = SHIP.height / 2;
const N = HULL.n;

/* --- hull surface --------------------------------------------------------- */

/** Station index for a normalised position t (0 = transom, 1 = bow). */
const stationOf = (t) => Math.min(N, Math.max(0, t * N));

function lerpArr(arr, f) {
  const i = Math.floor(f), j = Math.min(N, i + 1), k = f - i;
  return arr[i] * (1 - k) + arr[j] * k;
}

const xOf = (t) => -L / 2 + t * L;
const tOf = (x) => (x + L / 2) / L;

function section(t) {
  const f = stationOf(t);
  return {
    zPos: lerpArr(HULL.zPos, f) * HB,
    zNeg: lerpArr(HULL.zNeg, f) * HB,
    yTop: lerpArr(HULL.yUp, f) * HH,
    yBot: -lerpArr(HULL.yDn, f) * HH
  };
}

/** Spanwise fullness: 1 on the centreline, 0 at the chine. */
const bulge = (a) => Math.pow(Math.max(0, 1 - a * a), CHINE_SHARPNESS);

const smoothstep = (a, b, x) => {
  const k = Math.min(1, Math.max(0, (x - a) / (b - a)));
  return k * k * (3 - 2 * k);
};

/** Hull skin at (t, s): s in [-1, 1] across the beam, sign +1 dorsal. */
function skin(t, s, sign) {
  const sec = section(t);
  const z = (s >= 0 ? sec.zPos : sec.zNeg) * s;
  const yc = (sec.yTop + sec.yBot) / 2;
  const yE = sign > 0 ? sec.yTop : sec.yBot;
  return { x: xOf(t), y: yc + (yE - yc) * bulge(Math.abs(s)), z };
}

/** Hull skin height directly at a world z (used to seat the nacelles). */
function skinAtZ(t, z, sign) {
  const sec = section(t);
  const half = z >= 0 ? sec.zPos : sec.zNeg;
  const s = half > 1e-4 ? Math.max(-1, Math.min(1, z / half)) : 1;
  const yc = (sec.yTop + sec.yBot) / 2;
  const yE = sign > 0 ? sec.yTop : sec.yBot;
  return yc + (yE - yc) * bulge(Math.abs(s));
}

/* --- planar UV ------------------------------------------------------------ */
/* Projected from straight overhead, matching how the orthographics were drawn. */

const uOf = (x) => (x + L / 2) / L;
const vOf = (z, sign) => (sign > 0 ? (z + HB) : (HB - z)) / SHIP.beam;

/* --- mesh assembly -------------------------------------------------------- */

function Builder() {
  return {
    pos: [], uv: [], idx: [], groups: [], vOff: 0, iOff: 0,

    /** Add a quad grid. rows x cols vertices; verts(i, j) -> {x, y, z}. */
    grid(rows, cols, verts, sign, group) {
      const start = this.iOff, base = this.vOff;
      for (let i = 0; i < rows; i++) {
        for (let j = 0; j < cols; j++) {
          const p = verts(i, j);
          this.pos.push(p.x, p.y, p.z);
          this.uv.push(uOf(p.x), vOf(p.z, sign));
        }
      }
      for (let i = 0; i < rows - 1; i++) {
        for (let j = 0; j < cols - 1; j++) {
          const a = base + i * cols + j, b = a + 1, c = a + cols, d = c + 1;
          if (sign > 0) this.idx.push(a, b, c, b, d, c);
          else          this.idx.push(a, c, b, b, c, d);
        }
      }
      this.vOff += rows * cols;
      this.iOff = this.idx.length;
      this.groups.push({ start, count: this.iOff - start, group });
    },

    /** Add a triangle fan closing a ring. ring(j) -> {x, y, z}. */
    fan(cols, centre, ring, flip, sign, group) {
      const start = this.iOff, base = this.vOff;
      this.pos.push(centre.x, centre.y, centre.z);
      this.uv.push(uOf(centre.x), vOf(centre.z, sign));
      for (let j = 0; j < cols; j++) {
        const p = ring(j);
        this.pos.push(p.x, p.y, p.z);
        this.uv.push(uOf(p.x), vOf(p.z, sign));
      }
      for (let j = 0; j < cols - 1; j++) {
        if (flip) this.idx.push(base, base + 2 + j, base + 1 + j);
        else      this.idx.push(base, base + 1 + j, base + 2 + j);
      }
      this.vOff += cols + 1;
      this.iOff = this.idx.length;
      this.groups.push({ start, count: this.iOff - start, group });
    },

    finish() {
      const g = new THREE.BufferGeometry();
      g.setAttribute('position', new THREE.Float32BufferAttribute(this.pos, 3));
      g.setAttribute('uv', new THREE.Float32BufferAttribute(this.uv, 2));
      g.setIndex(this.idx);
      for (const grp of this.groups) g.addGroup(grp.start, grp.count, grp.group);
      g.computeVertexNormals();
      return g;
    }
  };
}

/* --- nacelles ------------------------------------------------------------- */
/* Measured off the top view: u is fractional length from the transom, z is a
   fraction of the half-beam. Each nacelle rises from the hull skin and settles
   back into it, so the body stays closed. */

const NACELLES = [
  // inboard pair — the big aft engines, emitters on the transom
  { z:  0.18, halfWidth: 0.115, u0: 0.00, u1: 0.52, rise: 0.62, peak: 0.16 },
  { z: -0.18, halfWidth: 0.115, u0: 0.00, u1: 0.52, rise: 0.62, peak: 0.16 },
  // outboard pair — integrated into the flanks, emitters at mid-hull
  { z:  0.624, halfWidth: 0.175, u0: 0.10, u1: 0.80, rise: 0.78, peak: 0.42 },
  { z: -0.624, halfWidth: 0.175, u0: 0.10, u1: 0.80, rise: 0.78, peak: 0.42 }
];

const RIB = 72, LONG = 40;

/** Rise profile for a nacelle: zero at both ends, full over the body, blunt at
    the transom, and forced back to zero wherever the hull is too narrow to
    carry it — otherwise the nacelle would hang outside the plan silhouette. */
function nacelleRise(nac, u) {
  if (u < nac.u0 || u > nac.u1) return 0;
  const zc = nac.z * HB, hw = nac.halfWidth * HB;
  const inA = nac.u0 <= 0.001 ? 1 : smoothstep(nac.u0, nac.u0 + 0.06, u);
  const outA = smoothstep(nac.u1, nac.u1 - 0.22, u);
  const sec = section(u);
  const half = zc >= 0 ? sec.zPos : sec.zNeg;
  const room = smoothstep(0, 0.09 * HB, half - (Math.abs(zc) + hw));
  return nac.rise * HH * Math.min(inA, outA) * room;
}

function addNacelle(b, nac, sign) {
  const zc = nac.z * HB, hw = nac.halfWidth * HB;
  const riseAt = (u) => nacelleRise(nac, u);

  b.grid(LONG + 1, RIB + 1, (i, j) => {
    const u = nac.u0 + (i / LONG) * (nac.u1 - nac.u0);
    const s = (j / RIB) * 2 - 1;
    const sec = section(u);
    const zRaw = zc + s * hw;
    const lim = zRaw >= 0 ? sec.zPos : sec.zNeg;
    const z = Math.sign(zRaw) * Math.min(Math.abs(zRaw), lim);
    const base = skinAtZ(u, z, sign);
    return { x: xOf(u), y: base + sign * riseAt(u) * bulge(Math.abs(s)), z };
  }, sign, sign > 0 ? 0 : 1);
}

/* --- hull ----------------------------------------------------------------- */

function buildHullGeometry() {
  const b = Builder();

  for (const sign of [1, -1]) {
    b.grid(N + 1, SPAN_SEGMENTS + 1, (i, j) => {
      const t = i / N;
      const s = (j / SPAN_SEGMENTS) * 2 - 1;
      return skin(t, s, sign);
    }, sign, sign > 0 ? 0 : 1);
  }

  // close the transom and the bow
  for (const t of [0, 1]) {
    for (const sign of [1, -1]) {
      const sec = section(t);
      const centre = { x: xOf(t), y: (sec.yTop + sec.yBot) / 2, z: 0 };
      b.fan(SPAN_SEGMENTS + 1, centre,
        (j) => skin(t, (j / SPAN_SEGMENTS) * 2 - 1, sign),
        (t === 0) === (sign > 0), sign, sign > 0 ? 0 : 1);
    }
  }

  for (const nac of NACELLES) {
    addNacelle(b, nac, +1);
    addNacelle(b, nac, -1);
  }

  return b.finish();
}

/* --- technical wireframe -------------------------------------------------- */

function buildWireGeometry() {
  const pts = [];
  const seg = (a, c) => pts.push(a.x, a.y, a.z, c.x, c.y, c.z);

  for (let i = 0; i < N; i++) {
    for (const s of [1, -1]) seg(skin(i / N, s, 1), skin((i + 1) / N, s, 1));
  }
  for (const s of [-0.85, -0.6, -0.35, 0, 0.35, 0.6, 0.85]) {
    for (const sign of [1, -1]) {
      for (let i = 0; i < N; i++) seg(skin(i / N, s, sign), skin((i + 1) / N, s, sign));
    }
  }
  for (let i = 0; i <= N; i += 8) {
    for (const sign of [1, -1]) {
      for (let j = 0; j < SPAN_SEGMENTS; j++) {
        seg(skin(i / N, (j / SPAN_SEGMENTS) * 2 - 1, sign),
            skin(i / N, ((j + 1) / SPAN_SEGMENTS) * 2 - 1, sign));
      }
    }
  }
  for (const nac of NACELLES) {
    const zc = nac.z * HB, hw = nac.halfWidth * HB;
    for (const sign of [1, -1]) {
      for (const s of [-1, 0, 1]) {
        for (let i = 0; i < 40; i++) {
          const ua = nac.u0 + (i / 40) * (nac.u1 - nac.u0);
          const ub = nac.u0 + ((i + 1) / 40) * (nac.u1 - nac.u0);
          const z = zc + s * hw;
          const ra = (u) => nacelleRise(nac, u);
          seg({ x: xOf(ua), y: skinAtZ(ua, z, sign) + sign * ra(ua) * bulge(Math.abs(s)), z },
              { x: xOf(ub), y: skinAtZ(ub, z, sign) + sign * ra(ub) * bulge(Math.abs(s)), z });
        }
      }
    }
  }

  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pts, 3));
  return g;
}

/* --- textures ------------------------------------------------------------- */

/** Isolate the warm pixels — engines, bussards, heat vanes — as an emissive map. */
function emissiveFrom(image) {
  const c = document.createElement('canvas');
  c.width = image.width; c.height = image.height;
  const g = c.getContext('2d');
  g.drawImage(image, 0, 0);
  const d = g.getImageData(0, 0, c.width, c.height);
  const p = d.data;
  for (let k = 0; k < p.length; k += 4) {
    const r = p[k], gg = p[k + 1], b = p[k + 2];
    if (r > 105 && r - b > 45 && r - gg > 20) {
      const f = Math.min(1, (r - b) / 140);
      p[k] = r * f; p[k + 1] = gg * f * 0.8; p[k + 2] = b * f * 0.5;
    } else {
      p[k] = p[k + 1] = p[k + 2] = 0;
    }
  }
  g.putImageData(d, 0, 0);
  const t = new THREE.CanvasTexture(c);
  t.flipY = false;
  t.colorSpace = THREE.SRGBColorSpace;
  return t;
}

function loadShellTexture(url, material, onReady) {
  new THREE.TextureLoader().load(url, (tex) => {
    tex.flipY = false;
    tex.colorSpace = THREE.SRGBColorSpace;
    tex.anisotropy = 8;
    tex.wrapS = tex.wrapT = THREE.ClampToEdgeWrapping;
    material.map = tex;
    material.emissiveMap = emissiveFrom(tex.image);
    material.emissive = new THREE.Color(0xffffff);
    material.emissiveIntensity = 1.25;
    material.color.setHex(0xffffff);
    material.needsUpdate = true;
    if (onReady) onReady();
  });
}

/* --- build ---------------------------------------------------------------- */

export function buildVictory(onTexturesReady) {
  const root = new THREE.Group();
  root.name = 'USS_VICTORY';

  const base = () => new THREE.MeshStandardMaterial({
    color: 0x5b6169, roughness: 0.64, metalness: 0.38, side: THREE.DoubleSide
  });

  const matDorsal = base();
  const matVentral = base();

  const hull = new THREE.Mesh(buildHullGeometry(), [matDorsal, matVentral]);
  hull.name = 'hull';
  root.add(hull);

  const wire = new THREE.LineSegments(
    buildWireGeometry(),
    new THREE.LineBasicMaterial({ color: 0xffa24c, transparent: true, opacity: 0.9 })
  );
  wire.name = 'hull_wireframe';
  wire.visible = false;
  root.add(wire);

  let pending = 2;
  const done = () => { if (--pending === 0 && onTexturesReady) onTexturesReady(); };
  loadShellTexture('refs/tex-dorsal.png', matDorsal, done);
  loadShellTexture('refs/tex-ventral.png', matVentral, done);

  root.userData.setMode = function (mode) {
    const isWire = (mode === 'wireframe');
    hull.visible = !isWire;
    wire.visible = isWire;
  };

  root.userData.hull = hull;
  return root;
}
